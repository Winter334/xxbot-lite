"""NPC 仙侠道号池。

主人风格：仙侠沉浸派，无任何 NPC 标识前缀。
姓 30+ / 字 100+，generate_xianxia_name 返回 "{姓}{字1}{字2}" 三字名。
"""

from __future__ import annotations

import random


# 30 个仙侠姓
_SURNAMES: tuple[str, ...] = (
    "云", "叶", "苏", "墨", "白", "玄", "玉", "凌", "夜", "君",
    "南", "北", "东", "西", "顾", "萧", "慕", "陆", "司", "上官",
    "欧阳", "南宫", "公孙", "轩辕", "司徒", "东方", "西门", "独孤", "纳兰", "宇文",
)


# 100 个仙侠风骨字（用于双字名）
_NAME_CHARS: tuple[str, ...] = (
    "尘", "霄", "渊", "溟", "璃", "瑶", "霜", "雪", "月", "星",
    "辰", "璇", "瑾", "玦", "珩", "璟", "煊", "曜", "羲", "皓",
    "昭", "晗", "晞", "晨", "晟", "昀", "昕", "旭", "旸", "旻",
    "渺", "潇", "湘", "瀚", "澜", "渚", "汐", "沐", "泠", "灏",
    "翊", "翎", "翰", "翼", "翀", "翟", "翯", "羽", "鸢", "鸿",
    "悟", "弈", "言", "无", "归", "知", "见", "藏", "隐", "寂",
    "清", "净", "妙", "玄", "真", "虚", "空", "寒", "冰", "霁",
    "枫", "桑", "梅", "兰", "竹", "菊", "莲", "荷", "棠", "梨",
    "心", "魂", "魄", "灵", "神", "意", "念", "思", "忆", "梦",
    "九", "千", "万", "孤", "独", "苍", "穹", "天", "地", "生",
)


def generate_xianxia_name(rng: random.Random) -> str:
    """生成仙侠风格三字名（双字字组合自动去重）。"""
    surname = rng.choice(_SURNAMES)
    # 双字名，确保两字不同
    char1 = rng.choice(_NAME_CHARS)
    char2 = rng.choice(_NAME_CHARS)
    while char2 == char1:
        char2 = rng.choice(_NAME_CHARS)
    return f"{surname}{char1}{char2}"
